"""Generate the JSON Schema and TypeScript types of the wire protocol from the msgspec structs.

    uv run --project apps/server python tools/gen_protocol.py          # write files
    uv run --project apps/server python tools/gen_protocol.py --check  # fail if the files are stale

Outputs: packages/protocol/schema.json and packages/protocol/src/index.ts. Never edit them by hand.
"""

from __future__ import annotations

import argparse
import json
import sys
import typing
from pathlib import Path

import msgspec
from msgspec import inspect as mi

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "apps" / "server"))

from app.realtime import protocol as pr  # noqa: E402

SCHEMA_PATH = ROOT / "packages" / "protocol" / "schema.json"
TS_PATH = ROOT / "packages" / "protocol" / "src" / "index.ts"

LITERAL_ALIASES = ("Mode", "Difficulty", "RoomPhase", "RejectCode", "ErrorCode", "BombStatsMode")


def literal_names() -> dict[frozenset[object], str]:
    return {frozenset(typing.get_args(getattr(pr, name))): name for name in LITERAL_ALIASES}


def ts_type(t: mi.Type, aliases: dict[frozenset[object], str]) -> str:
    match t:
        case mi.IntType() | mi.FloatType():
            return "number"
        case mi.StrType():
            return "string"
        case mi.BoolType():
            return "boolean"
        case mi.NoneType():
            return "null"
        case mi.LiteralType():
            name = aliases.get(frozenset(t.values))
            if name:
                return name
            return " | ".join(json.dumps(v) for v in t.values)
        case mi.ListType():
            inner = ts_type(t.item_type, aliases)
            return f"({inner})[]" if "|" in inner else f"{inner}[]"
        case mi.DictType():
            return f"Record<string, {ts_type(t.value_type, aliases)}>"
        case mi.StructType():
            return t.cls.__name__
        case mi.UnionType():
            parts = [ts_type(x, aliases) for x in t.types]
            return " | ".join(dict.fromkeys(parts))
        case mi.Metadata():
            return ts_type(t.type, aliases)
        case _:
            raise TypeError(f"unsupported type in protocol: {t!r}")


def struct_to_ts(info: mi.StructType, aliases: dict[frozenset[object], str], client: bool) -> str:
    lines = [f"export interface {info.cls.__name__} {{"]
    if info.tag_field:
        lines.append(f"  {info.tag_field}: {json.dumps(info.tag)};")
    for field in info.fields:
        t = field.type
        # An optional field with no default and no factory is an UNSET field: msgspec omits it from the wire.
        optional = not field.required and field.default is msgspec.NODEFAULT and field.default_factory is msgspec.NODEFAULT
        if client and not field.required:
            optional = True
        mark = "?" if optional else ""
        lines.append(f"  {field.name}{mark}: {ts_type(t, aliases)};")
    lines.append("}")
    return "\n".join(lines)


def collect(union: typing.Any) -> list[mi.StructType]:
    return [mi.type_info(cls) for cls in typing.get_args(union)]  # type: ignore[misc]


def generate() -> tuple[str, str]:
    aliases = literal_names()
    client = collect(pr.ClientMessage)
    server = collect(pr.ServerMessage)
    views = [
        pr.SettingsView,
        pr.PlayerView,
        pr.TurnView,
        pr.WordView,
        pr.ResultRow,
        pr.DayStat,
        pr.BombWordStat,
        pr.BombRecentWord,
        pr.BombStatsSummary,
        pr.BombStatsView,
    ]
    out = [
        "// AUTO-GENERATED by tools/gen_protocol.py from apps/server/app/realtime/protocol.py. Do not edit.",
        "",
        f"export const PROTOCOL_VERSION = {pr.PROTOCOL_VERSION};",
        "",
    ]
    for name in LITERAL_ALIASES:
        values = typing.get_args(getattr(pr, name))
        out.append(f"export type {name} = {' | '.join(json.dumps(v) for v in values)};")
    out.append("")
    for cls in views:
        out += [struct_to_ts(mi.type_info(cls), aliases, client=False), ""]  # type: ignore[arg-type]
    out.append("// ---- client -> server")
    for info in client:
        out += [struct_to_ts(info, aliases, client=True), ""]
    out.append(f"export type ClientMessage = {' | '.join(i.cls.__name__ for i in client)};")
    out += ["", "// ---- server -> client"]
    for info in server:
        out += [struct_to_ts(info, aliases, client=False), ""]
    out.append(f"export type ServerMessage = {' | '.join(i.cls.__name__ for i in server)};")
    out.append("")
    out.append("export type ServerMessageType = ServerMessage['t'];")
    out.append("export type ClientMessageType = ClientMessage['t'];")
    out.append("")
    _, components = msgspec.json.schema_components([pr.ClientMessage, pr.ServerMessage])
    schema = json.dumps(
        {
            "$comment": "AUTO-GENERATED by tools/gen_protocol.py. Do not edit.",
            "client": msgspec.json.schema(pr.ClientMessage),
            "server": msgspec.json.schema(pr.ServerMessage),
            "components": components,
        },
        indent=2,
        ensure_ascii=False,
    )
    return "\n".join(out), schema + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    ts, schema = generate()
    if args.check:
        stale = [
            p.name
            for p, text in ((TS_PATH, ts), (SCHEMA_PATH, schema))
            if not p.exists() or p.read_text(encoding="utf-8") != text
        ]
        if stale:
            sys.exit(f"Generated protocol files are stale: {', '.join(stale)}. Run `make protocol`.")
        print("protocol files are up to date")
        return
    TS_PATH.parent.mkdir(parents=True, exist_ok=True)
    TS_PATH.write_text(ts, encoding="utf-8", newline="\n")
    SCHEMA_PATH.write_text(schema, encoding="utf-8", newline="\n")
    print(f"wrote {TS_PATH.relative_to(ROOT)} and {SCHEMA_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
